const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const elements = new Map();
const element = id => {
  if (!elements.has(id)) elements.set(id, {textContent:'',innerHTML:'',classList:{toggle(){},add(){}}});
  return elements.get(id);
};
const requests = [];
const context = vm.createContext({
  document:{addEventListener(){},getElementById:element},
  API:{get(endpoint,params){ return new Promise((resolve,reject)=>requests.push({endpoint,params,resolve,reject})); }}
});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../assets/js/pages/dashboard.js'),'utf8'), context);
const row = {personal_id:1,estado_evaluado:'ASISTIO',turno_id:1,hora_prog_inicio:'07:00',hora_prog_fin:'13:00',hora_entrada:'07:00',area_id:7,area_nombre:'Área de prueba'};
(async () => {
  vm.runInContext("dashState.fecha='2026-11-11';",context);
  const first = vm.runInContext('cargarAsistenciaDashboard()',context);
  vm.runInContext("dashState.fecha='2026-11-12';",context);
  const second = vm.runInContext('cargarAsistenciaDashboard()',context);
  requests[2].resolve({ok:true,fecha:'2026-11-12',calidad:null,pendientes:null,biometrico:null});
  requests[3].resolve({ok:true,conexion_sql:true,asistencias:[row]});
  await second;
  requests[0].resolve({ok:true,fecha:'2026-11-11',calidad:null,pendientes:null,biometrico:null});
  requests[1].resolve({ok:true,conexion_sql:true,asistencias:[]});
  await first;
  assert.equal(element('dashKpiProgramados').textContent,1);
  assert.ok(element('dashConnectionStatus').textContent.includes('2026-11-12'));
  assert.ok(element('dashCoverageBody').innerHTML.includes('Área de prueba'));
  const third = vm.runInContext('cargarAsistenciaDashboard()',context);
  assert.ok(element('dashTableBody').innerHTML.includes('skeleton-table-row'));
  assert.ok(element('dashBiometric').innerHTML.includes('skeleton'));
  assert.equal(element('dashNextPage').disabled,true);
  requests[4].reject(new Error('Servidor sin conexión'));
  requests[5].resolve({ok:true,conexion_sql:false,consulta:{respaldo_guardado_en:'2026-11-12 08:00:00'},asistencias:[]});
  await third;
  assert.ok(element('dashConnectionStatus').textContent.includes('Respaldo'));
  assert.ok(element('dashConnectionStatus').textContent.includes('08:00:00'));
  assert.equal(element('dashDataSource').textContent,'Respaldo de consulta');
  assert.ok(element('dashDataQuality').textContent.includes('No disponible'));
  assert.equal(element('dashKpiProgramados').textContent,0);
  const fourth = vm.runInContext('cargarAsistenciaDashboard()',context);
  requests[6].reject(new Error('Sin SQL'));
  requests[7].reject(new Error('Sesión vencida'));
  await fourth;
  assert.equal(element('dashKpiProgramados').textContent,'—');
  assert.ok(element('dashTableBody').innerHTML.includes('Sesión vencida'));
  assert.equal(element('dashDataSource').textContent,'Asistencia sin confirmar');
  context.pagingRows = Array.from({length:25}, (_,index) => ({...row,personal_id:index+1,nombre_completo:`Trabajador ${index+1}`}));
  vm.runInContext('dashState.todosRegistros=pagingRows; dashState.loading=false; dashState.page=1; actualizarDashboardWorkerSelect(); renderTablaAsistencia();',context);
  assert.equal((element('dashTableBody').innerHTML.match(/<tr>/g)||[]).length,10);
  assert.equal(element('dashFooterCount').textContent,'Mostrando 1 a 10 de 25 trabajadores');
  assert.equal(element('dashPrevPage').disabled,true);
  vm.runInContext('dashState.page=2; renderTablaAsistencia();',context);
  assert.equal(element('dashFooterCount').textContent,'Mostrando 11 a 20 de 25 trabajadores');
  vm.runInContext('dashState.page=3; renderTablaAsistencia();',context);
  assert.equal((element('dashTableBody').innerHTML.match(/<tr>/g)||[]).length,5);
  assert.equal(element('dashNextPage').disabled,true);
  vm.runInContext("dashState.personalId='25'; renderTablaAsistencia();",context);
  assert.equal(element('dashFooterCount').textContent,'Mostrando 1 a 1 de 1 trabajadores');
  assert.ok(element('dashTableBody').innerHTML.includes('Trabajador 25'));
  assert.equal(vm.runInContext('dashState.page',context),1);
  vm.runInContext("dashState.todosRegistros=[pagingRows[0]]; actualizarDashboardWorkerSelect();",context);
  assert.equal(vm.runInContext('dashState.personalId',context),'');
  vm.runInContext("dashState.busqueda='sin coincidencias'; renderTablaAsistencia();",context);
  assert.equal(element('dashFooterCount').textContent,'Mostrando 0 a 0 de 0 trabajadores');
  assert.equal(element('dashNextPage').disabled,true);
  console.log('OK: carga con skeletons, respuestas fuera de orden, respaldo, paginación de 10 y selección de trabajador.');
})().catch(error => { console.error(error); process.exitCode=1; });
