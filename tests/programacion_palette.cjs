const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const nodes = {quickShiftPaletteList: {innerHTML: ''}, customTurnoCodigo: {value: '', innerHTML: ''}};
const context = vm.createContext({console, Date, document: {addEventListener() {}, getElementById: id => nodes[id] || null}, window: {}, intval: Number});
vm.runInContext(fs.readFileSync('assets/js/pages/programacion.js', 'utf8') + '\nglobalThis.state=progState;', context);
context.state.turnosDisponibles = [{turno_id:42,codigo:'X42',nombre:'Turno registrado',activo:1,horas_computables:7}];
context.state.catalogTurnos = {X42: {horas:7}, M: {nombre:'Alias histórico',horas:6}, LIB: {nombre:'Libre',horas:0}};
context.renderPaletteModal(context.state.catalogTurnos);
assert.ok(nodes.quickShiftPaletteList.innerHTML.includes('Turno registrado'));
assert.ok(!nodes.quickShiftPaletteList.innerHTML.includes('Alias histórico'));
assert.ok(nodes.quickShiftPaletteList.innerHTML.includes('Descansos y ausencias'));
assert.ok(nodes.customTurnoCodigo.innerHTML.includes('X42'));
assert.ok(!nodes.customTurnoCodigo.innerHTML.includes('Alias histórico'));
context.state.turnosDisponibles=[];
context.renderPaletteModal({});
assert.equal(nodes.customTurnoCodigo.innerHTML,'');
assert.equal(nodes.quickShiftPaletteList.innerHTML,'');
console.log('OK: 7 comprobaciones de selección real, equivalencias fuera de la paleta, ausencias separadas y catálogo vacío.');
